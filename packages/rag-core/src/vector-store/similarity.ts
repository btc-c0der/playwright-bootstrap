/**
 * Brute-force cosine similarity — the local store's only "algorithm". At the
 * corpus sizes this ships for (thousands, not millions, of specs/tests/CI
 * failures per team) a linear scan in JS is sub-100ms and not worth trading
 * for an ANN index; see docs/rag-coverage.md for when to graduate off it.
 */
export function cosineSimilarity(a: number[], b: number[]): number {
  if (a.length !== b.length) {
    throw new Error(`cosineSimilarity: dimension mismatch (${a.length} vs ${b.length})`);
  }
  let dot = 0;
  let normA = 0;
  let normB = 0;
  for (let i = 0; i < a.length; i++) {
    const ai = a[i] ?? 0;
    const bi = b[i] ?? 0;
    dot += ai * bi;
    normA += ai * ai;
    normB += bi * bi;
  }
  if (normA === 0 || normB === 0) return 0;
  return dot / (Math.sqrt(normA) * Math.sqrt(normB));
}
